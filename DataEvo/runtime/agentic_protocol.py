"""Shared, text-only terminal protocol for synthesis, GRPO and Harbor evaluation.

Observations use user messages so standard chat templates can represent them;
only assistant spans are optimized. Commands always execute in a Harbor sandbox.
"""
import json
import math

SYSTEM = ('You are solving a task in a persistent Linux sandbox. Reply with exactly one JSON object: '
          '{"command":"shell command"} to execute a command, or {"final":"summary"} to finish. '
          'Tool results arrive as user messages prefixed TOOL_RESULT. Files persist between commands; '
          'each command starts a fresh shell, so use explicit working directories. '
          'Do not include markdown fences or text outside the JSON object.')


def prompt(instruction):
    return [{'role': 'system', 'content': SYSTEM}, {'role': 'user', 'content': instruction}]


def action(text):
    value = json.loads(text)
    if not isinstance(value, dict) or set(value) not in ({'command'}, {'final'}):
        raise ValueError('expected exactly one command or final field')
    key = next(iter(value))
    if not isinstance(value[key], str) or not value[key].strip():
        raise ValueError('action must be a nonempty string')
    return key, value[key]


def observation(result, max_chars):
    # Bound *both* fields together, preserving valid JSON and an explicit truncation flag.
    stdout, stderr = str(result.get('stdout') or ''), str(result.get('stderr') or '')
    return {'role': 'user', 'content': 'TOOL_RESULT ' + json.dumps({
        'stdout': stdout[:max_chars // 2], 'stderr': stderr[:max_chars // 2],
        'return_code': result.get('return_code'),
        'truncated': len(stdout) > max_chars // 2 or len(stderr) > max_chars // 2}, ensure_ascii=False)}


def reward_value(rewards, key='reward'):
    value = rewards.get(key) if isinstance(rewards, dict) else None
    if isinstance(value, bool) or not isinstance(value, (float, int)) or not math.isfinite(value) or not 0 <= value <= 1:
        raise ValueError(f'verifier must return finite {key} in [0,1]')
    return float(value)


def token_spans(tokenizer, messages, prompt_count):
    """Reject templates that rewrite history; never silently approximate a loss mask.

    Assistant headers are supplied by the template, not generated by the model.
    Only assistant content and its closing tokens receive loss.
    """
    def encode(part, generation=False):
        return list(tokenizer.apply_chat_template(part, tokenize=True,
                    add_generation_prompt=generation, enable_thinking=False, return_dict=False))
    initial = encode(messages[:prompt_count], True)
    previous, mask = initial, [0] * len(initial)
    for end in range(prompt_count + 1, len(messages) + 1):
        assistant = messages[end - 1]['role'] == 'assistant'
        if assistant:
            prefix = encode(messages[:end - 1], True)
            if prefix[:len(previous)] != previous:
                raise ValueError('chat template rewrites history before assistant generation')
            mask.extend([0] * (len(prefix) - len(previous)))
            previous = prefix
        current = encode(messages[:end])
        if current[:len(previous)] != previous:
            raise ValueError('chat template is not prefix-stable; unsupported token alignment')
        added = current[len(previous):]
        generated = [int(assistant)] * len(added)
        if assistant and tokenizer.eos_token_id in added:
            # A chat template may append a newline after EOS. That separator was
            # inserted by the template, not sampled by the policy.
            eos = added.index(tokenizer.eos_token_id)
            generated[eos + 1:] = [0] * (len(added) - eos - 1)
        mask.extend(generated)
        previous = current
    return initial, previous[len(initial):], mask[len(initial):]
